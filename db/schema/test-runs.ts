import {
  pgTable,
  uuid,
  text,
  integer,
  jsonb,
  timestamp,
} from "drizzle-orm/pg-core";

// One row per executed run. Deliberately not a foreign key to `tests`: a run
// report must outlive the test it came from, so the title is copied.
export type RunStep = {
  index: number;
  nodeId: string;
  action: string;
  detail: string;
  status: "pending" | "running" | "passed" | "failed" | "stopped";
  startedAt: string | null;
  finishedAt: string | null;
  durationMs: number | null;
  waitedMs: number;
  error: string | null;
};

export type RunLogEntry = {
  at: string;
  label: string;
  detail: string;
  kind: "info" | "success" | "warning";
  // The step it happened during, when it was during one.
  step: number | null;
};

export const testRuns = pgTable("test_runs", {
  id: uuid("id").defaultRandom().primaryKey(),
  // Generated by the bridge; makes saving a report idempotent.
  runId: text("run_id").notNull().unique(),
  testId: uuid("test_id"),
  title: text("title").notNull(),
  status: text("status").notNull(),
  startedAt: timestamp("started_at", { withTimezone: true }).notNull(),
  finishedAt: timestamp("finished_at", { withTimezone: true }),
  durationMs: integer("duration_ms"),
  error: text("error"),
  failedStep: integer("failed_step"),
  stepDelaySeconds: integer("step_delay_seconds"),
  device: jsonb("device").$type<{ model: string | null; android: string | null }>(),
  steps: jsonb("steps").$type<RunStep[]>().notNull().default([]),
  log: jsonb("log").$type<RunLogEntry[]>().notNull().default([]),
  screenshot: text("screenshot"),
  createdAt: timestamp("created_at", { withTimezone: true }).defaultNow().notNull(),
});
